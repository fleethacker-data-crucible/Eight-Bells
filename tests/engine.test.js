'use strict';
const assert=require('assert');
const fs=require('fs');
const path=require('path');
const engine=require('../web/engine.js');
const sample=name=>fs.readFileSync(path.join(__dirname,'..','samples',name),'utf8');
const run=(name,format)=>{const parsed=engine.parse(sample(name),format||'auto');return {...parsed,analysis:engine.analyze(parsed.entries)};};
const normal=run('engineering_normal.log');
assert.strictEqual(normal.format,'text');
assert.strictEqual(normal.analysis.open.length,0);
assert.strictEqual(normal.analysis.findings.length,0);
const abnormal=run('engineering_discrepancy.txt');
assert(abnormal.analysis.findings.some(x=>x.type==='disposition'));
assert(!abnormal.analysis.findings.some(x=>x.type==='chronology'),'Date header must not be read as HHMM');
assert(engine.turnover({id:'abc',name:'Engineering test',entries:abnormal.entries,analysis:abnormal.analysis}).includes('Line '));
const repetition=run('engineering_repetition.log');
assert(repetition.analysis.findings.some(x=>x.type==='copy-forward'));
const chronology=run('engineering_chronology.txt');
assert(chronology.analysis.findings.some(x=>x.type==='chronology'));
const csv=run('readings.csv');
assert.strictEqual(csv.format,'csv');assert.strictEqual(csv.entries.length,8);
assert(csv.analysis.findings.some(x=>x.type==='copy-forward'));
const json=run('elog_export.json');
assert.strictEqual(json.format,'json');assert.strictEqual(json.entries.length,3);
const comma=engine.csv('timestamp,description\n0800,"Valve, test"\n0810,"He said ""OK"""');
assert.strictEqual(comma[1][1],'Valve, test');
assert.strictEqual(comma[2][1],'He said "OK"');
assert.throws(()=>engine.parse('{bad','json'));
assert.strictEqual(engine.parse('0800 No new discrepancies observed\n0830 No alarms reported','text').entries.filter(x=>x.issue).length,0);
const logA={id:'a',entries:abnormal.entries,analysis:abnormal.analysis};
const logB={id:'b',entries:abnormal.entries,analysis:abnormal.analysis};
assert(engine.candidates([logA,logB]).some(x=>x.title.toLowerCase().includes('pump')));
console.log('PASS: 11 deterministic ingestion, QA, turnover, and recurrence tests');
// Keep the controller regressions in the existing CI Node-test entry point.
require('./turnover.test.js');
