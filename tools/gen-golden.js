'use strict';
// Writes tests/golden/engine.golden.json from web/engine.js: parse, analyze, turnover and candidates for the synthetic
// samples and some inline edge cases. The PowerShell port (EightBells-Engine.ps1) is held to this file by tests/Engine-Test.ps1,
// and tests/engine-golden.test.js fails when engine.js changes without this file being regenerated.
// Run: node tools/gen-golden.js
const fs=require('fs');
const path=require('path');
const E=require('../web/engine.js');
const root=path.join(__dirname,'..');
const sample=name=>fs.readFileSync(path.join(root,'samples',name),'utf8');
const files=[
 ['engineering_normal.log','auto',0],['engineering_normal.log','text',15],['engineering_discrepancy.txt','auto',0],['engineering_repetition.log','auto',0],
 ['engineering_chronology.txt','auto',0],['quarterdeck_watch.txt','auto',0],['damage_control_watch.txt','auto',0],['security_patrol.txt','auto',0],
 ['multiwatch_history.txt','auto',0],['noisy_ocr.txt','auto',0],['readings.csv','auto',0],['readings.csv','csv',30],['elog_export.json','auto',0]
];
const inline=[
 {name:'inline-csv-quoted',format:'csv',intervalMinutes:0,content:'timestamp,equipment,description\r\n0800,"Pump A","Leak found, ""minor"", near seal"\r\n0830,Pump A,"Leak repaired\nand cleared"\r\n\r\n0900,Valve 3,Routine check\r\n'},
 {name:'inline-json-entries',format:'auto',intervalMinutes:0,content:'{"entries":[{"time":"08:00","equipment":"Pump A","text":"leak found"},"0830 leak repaired",{"timestamp":"2026-10-30T09:15:00","description":"Fan 2 alarm"}]}'},
 {name:'inline-json-array',format:'json',intervalMinutes:60,content:'[{"datetime":"2026-10-30 08:00","asset":"Tag 7","message":"intermittent fault"},{"datetime":"2026-10-30 10:30","asset":"Tag 7","message":"fault persists"}]'},
 {name:'inline-text-crlf',format:'text',intervalMinutes:30,content:'0800 Watch assumed\r\n0900 Generator 1 failed\r\n\r\n0905 Generator 1 restored\r\n2350 Late entry\r\n0010 After midnight'},
 {name:'inline-negative',format:'text',intervalMinutes:0,content:'0800 No new discrepancies observed\n0830 Valve 3 fault\n0900 Valve 3 restored\n0930 Without incident'},
 {name:'inline-repeat',format:'text',intervalMinutes:0,content:'0800 Pump A pressure normal\n0900 Pump A pressure normal\n1000 Pump A pressure normal\n1100 Pump A pressure normal'},
 {name:'inline-empty',format:'text',intervalMinutes:0,content:''},
 {name:'inline-no-times',format:'text',intervalMinutes:0,content:'Watch assumed\nPump B alarm\nSupervisor notified\nrounds complete'}
];
function build(c){
 const content=c.content!==undefined?c.content:sample(c.file);
 const parsed=E.parse(content,c.format);
 const analysis=E.analyze(parsed.entries,{intervalMinutes:c.intervalMinutes});
 const log={id:'golden-'+c.name,name:c.name,imported:'2026-10-30T00:00:00Z',entries:parsed.entries,analysis};
 const entry=Object.assign({},c);
 return Object.assign(entry,{expect:{format:parsed.format,entries:parsed.entries.map(e=>({id:e.id,line:e.line,time:e.time,text:e.text,equipment:e.equipment,issue:e.issue,resolution:e.resolution})),analysis,turnover:E.turnover(log)}});
}
function generate(){
 const cases=files.map(([file,format,intervalMinutes])=>({name:file+' ('+format+', '+intervalMinutes+' min)',file,format,intervalMinutes})).concat(inline).map(build);
 // Recurring-condition candidates need analysed logs; use the discrepancy and multiwatch samples twice each.
 const logOf=(file,id)=>{const p=E.parse(sample(file),'auto');return {id,entries:p.entries,analysis:E.analyze(p.entries)};};
 const pairs=[
  {name:'discrepancy x2',logs:[['engineering_discrepancy.txt','a'],['engineering_discrepancy.txt','b']]},
  {name:'multiwatch + discrepancy',logs:[['multiwatch_history.txt','m'],['engineering_discrepancy.txt','d'],['multiwatch_history.txt','m2']]},
  {name:'single log',logs:[['engineering_discrepancy.txt','only']]}
 ].map(p=>({name:p.name,logs:p.logs,expect:E.candidates(p.logs.map(([f,id])=>logOf(f,id)))}));
 return {note:'Generated by tools/gen-golden.js from web/engine.js. Do not edit by hand.',cases,candidates:pairs};
}
if(require.main===module){
 fs.mkdirSync(path.join(root,'tests','golden'),{recursive:true});
 fs.writeFileSync(path.join(root,'tests','golden','engine.golden.json'),JSON.stringify(generate(),null,1)+'\n');
 console.log('Wrote tests/golden/engine.golden.json');
}
module.exports={generate};
