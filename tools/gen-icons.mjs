// Generates web/icons.js from Lucide's SVG sources, so Eight Bells ships only the icons it uses
// and never loads anything from a CDN (docs/UNIFIED-UI.md section 6).
//   npm pack lucide-static@1.54.0 && tar -xzf lucide-static-1.54.0.tgz
//   node tools/gen-icons.mjs package/icons
// The output is committed; re-run only when the icon list changes.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const LUCIDE_VERSION = '1.54.0';
// Eight Bells icon name -> Lucide icon name.
const ICONS = {
  overview: 'layout-dashboard',
  ingest: 'file-input',
  quality: 'clipboard-check',
  turnover: 'arrow-left-right',
  memory: 'library',
  settings: 'settings',
  power: 'power',
  refresh: 'refresh-cw',
  plus: 'plus',
  arrowRight: 'arrow-right',
  download: 'download',
  copy: 'copy',
  save: 'save',
  sparkles: 'sparkles',
  scan: 'scan-text',
  warning: 'triangle-alert',
  themeSystem: 'sun-moon',
  themeLight: 'sun',
  themeDark: 'moon',
  collapse: 'panel-left-close',
  expand: 'panel-left-open',
};

// Shared fleet comment stripper (Bowerbird, Capstan, Eight-Bells, Gangplank, PacketRat).
function commentEnd(s, from) {
  for (let j = from; j < s.length - 2; j++) {
    if (s[j] !== '-' || s[j + 1] !== '-') continue;
    if (s[j + 2] === '>') return j + 3;
    if (s[j + 2] === '!' && s[j + 3] === '>') return j + 4;
  }
  return -1;
}
function stripOnce(s) {
  let out = '';
  let i = 0;
  while (i < s.length) {
    const start = s.indexOf('<!--', i);
    if (start < 0) return out + s.slice(i);
    out += s.slice(i, start);
    if (s[start + 4] === '>') { i = start + 5; continue; }
    if (s[start + 4] === '-' && s[start + 5] === '>') { i = start + 6; continue; }
    const end = commentEnd(s, start + 4);
    if (end < 0) return out;
    i = end;
  }
  return out;
}
export function stripHtmlComments(input) {
  let cur = String(input);
  let prev;
  do { prev = cur; cur = stripOnce(cur); } while (cur !== prev);
  return cur;
}

// Inner markup of a Lucide SVG: no comment, no outer <svg>, newlines collapsed.
// Well-formed Lucide 1.54.0 files produce the same string as the old replace chain.
export function svgInner(svg) {
  return stripHtmlComments(svg)
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '')
    .trim();
}

function main() {
  const dir = process.argv[2];
  if (!dir) {
    console.error('usage: node tools/gen-icons.mjs <lucide-static>/icons');
    process.exit(1);
  }
  const entries = Object.entries(ICONS).map(([name, lucide]) => {
    const svg = readFileSync(path.join(dir, `${lucide}.svg`), 'utf8');
    const inner = svgInner(svg);
    return `  ${name}: ${JSON.stringify(inner)}, // ${lucide}`;
  });

  const out = `// GENERATED by tools/gen-icons.mjs from Lucide ${LUCIDE_VERSION} (ISC licence, https://lucide.dev). Do not edit.
// Drawn at 16 px in controls and 20 px in navigation, 1.75 px stroke, currentColor (docs/UNIFIED-UI.md section 6).
// Static markup uses <span data-icon="name" data-size="20"></span>; hydrate() fills them in.
(function (root) {
  'use strict';
  const paths = {
${entries.join('\n')}
  };
  function svg(name, size) {
    const s = Number(size) || 16;
    return '<svg class="icon" width="' + s + '" height="' + s + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" ' +
      'stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' + (paths[name] || '') + '</svg>';
  }
  function hydrate(scope) {
    (scope || document).querySelectorAll('[data-icon]').forEach(function (el) {
      el.innerHTML = svg(el.getAttribute('data-icon'), el.getAttribute('data-size'));
    });
  }
  root.EightBellsIcons = { svg: svg, hydrate: hydrate, names: Object.keys(paths) };
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
  const target = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'web', 'icons.js');
  writeFileSync(target, out);
  console.log(`wrote ${entries.length} icons to ${target}`);
}

const entry = process.argv[1];
if (entry && pathToFileURL(path.resolve(entry)).href === import.meta.url) main();
